"""Reproduce the fictional authoring pilot through its actual offline CLI.

Run from the repository with an explicitly selected empty disposable directory.
The prose below is authored demonstration input, never generated by the tool.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = (
    ("packet-a-conditional.json", "CONDITIONAL_SUPPORT"),
    ("packet-b-missing.json", "INDETERMINATE_MISSING"),
    ("packet-c-unsupported.json", "INDETERMINATE_UNSUPPORTED"),
    ("packet-d-conflict.json", "INDETERMINATE_CONFLICT"),
    ("packet-e-compatibility.json", "INDEPENDENT_CONDITIONALS_ONLY"),
)


def authored_correction(draft):
    """Supply this demonstration author's explicit fictional edits."""
    packet = draft["packet"]
    beacon = next(row for row in packet["claims"] if row["claim_id"] == "beacon")
    beacon.update(condition="PRESENT", value=True, limitation_refs=[], attribution={
        "actor_id": "fictional:b:correction-author",
        "statement_id": "statement-beacon-correction",
    })
    packet["reasoning"][0].update(condition="PRESENT", limitation_refs=[], explanation=(
        "Authored fictional correction: correction-author asserts beacon is lit at ctx/version 1. "
        "Under premise, that supplied assertion supports the stated conditional-flash "
        "explanation in retained 601.3d context. This is authored reasoning, not a computed "
        "permission decision or verification of the assertion."
    ))
    packet["limitations"] = [row for row in packet["limitations"] if row["limitation_id"] != "missing-beacon"]
    packet["conclusion"].update(kind="CONDITIONAL_SUPPORT", limitation_refs=["scope"], text=(
        "Authored fictional correction: under premise and correction-author's beacon assertion, "
        "the conditional-flash condition has conditional support for this beginning explanation. "
        "The assertion is unverified; applicable-effect completeness, other permission, later "
        "legality, compatible choices, payment and completion remain outside this conclusion; "
        "execution BLOCKED. The author supplied this conclusion."
    ))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", required=True, type=Path,
                        help="existing empty disposable local directory")
    args = parser.parse_args()
    workspace = args.workspace.absolute()
    if (not workspace.is_dir() or any(path.is_symlink() for path in (workspace, *workspace.parents))
            or any(workspace.iterdir())):
        parser.error("workspace must be an existing empty directory without symlinks")
    drafts = workspace / "drafts"
    drafts.mkdir()
    env = dict(os.environ, PYTHONPATH=str(ROOT / "src"))

    def cli(*arguments, error=None):
        command = [sys.executable, "-m", "proposed_spell_packets", "--workspace", str(workspace), *map(str, arguments)]
        print("$ " + shlex.join(command), flush=True)
        result = subprocess.run(command, cwd=ROOT, env=env, capture_output=True, text=True)
        if result.stdout:
            print(result.stdout, end="", flush=True)
        if result.stderr:
            print(result.stderr, end="", file=sys.stderr, flush=True)
        if error is not None:
            if result.returncode == 0 or error not in result.stdout + result.stderr:
                raise RuntimeError("expected structural rejection: " + error)
        elif result.returncode:
            raise RuntimeError("CLI failed with exit " + str(result.returncode))
        return result.stdout

    def save(path, value):
        path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    examples = {}
    prior_bytes = {}
    for name, outcome in EXAMPLES:
        draft_path = drafts / name
        cli("draft", "--example", name, "--output", draft_path)
        result = json.loads(cli("record", "--draft", draft_path))
        packet_id = result["packet_id"]
        packet_path = workspace / "packets" / (packet_id.removeprefix("sha256:") + ".json")
        raw = packet_path.read_bytes()
        packet = json.loads(raw)
        if packet["conclusion"]["kind"] != outcome:
            raise RuntimeError("retained example outcome changed: " + name)
        retained = ROOT / "reference-reviews" / "gameplay-rules-proposed-spell-evidence-packet-design" / name
        if raw != retained.read_bytes():
            raise RuntimeError("retained example bytes changed: " + name)
        view = cli("inspect", packet_id)
        if outcome not in view:
            raise RuntimeError("inspection omitted authored outcome: " + name)
        examples[name] = packet_id
        prior_bytes[packet_path] = raw

    original = examples["packet-b-missing.json"]
    correction_path = drafts / "correction.json"
    cli("draft", "--base", original, "--output", correction_path)
    correction = json.loads(correction_path.read_text(encoding="utf-8"))
    authored_correction(correction)
    save(correction_path, correction)
    before = set((workspace / "packets").iterdir())
    cli("record", "--draft", correction_path, error="HISTORICAL_OBSERVATION_MATERIAL_CHANGED")
    if before != set((workspace / "packets").iterdir()):
        raise RuntimeError("invalid correction left a packet")
    correction["packet"]["history"]["review_observations"] = []
    save(correction_path, correction)
    corrected = json.loads(cli("record", "--draft", correction_path))["packet_id"]
    cli("inspect", corrected)
    correction_record = workspace / "packets" / (corrected.removeprefix("sha256:") + ".json")
    prior_bytes[correction_record] = correction_record.read_bytes()

    review_path = drafts / "review.json"
    cli("draft", "--base", corrected, "--output", review_path)
    review = json.loads(review_path.read_text(encoding="utf-8"))
    review["packet"]["history"]["review_observations"].append({
        "authority": "HUMAN_REVIEW_OBSERVATION",
        "claim_refs": ["beacon", "premise"],
        "fictional": True,
        "observation_id": "review-correction",
        "reviewer_id": "fictional:b:second-reviewer",
        "step_refs": ["condition"],
        "supersedes_observation_ids": [],
        "text": (
            "Separately attributed fictional review of the correction: the new beacon "
            "assertion and authored explanation retain scope limitations and execution "
            "BLOCKED. This observation does not verify truth or represent actual owner "
            "approval, PM approval, or gameplay authority."
        ),
    })
    save(review_path, review)
    reviewed = json.loads(cli("record", "--draft", review_path))["packet_id"]
    cli("inspect", reviewed)
    history = cli("history", reviewed)
    for expected in (original, corrected, reviewed, "INDETERMINATE_MISSING", "review-1", "review-correction"):
        if expected not in history:
            raise RuntimeError("history omitted originating material: " + expected)
    for path, raw in prior_bytes.items():
        if path.read_bytes() != raw:
            raise RuntimeError("prior record changed: " + path.name)
    print(json.dumps({"examples": examples, "original_revision_1": original,
        "correction_revision_2": corrected, "review_revision_3": reviewed,
        "rejected_old_review": "HISTORICAL_OBSERVATION_MATERIAL_CHANGED",
        "prior_record_bytes_unchanged": True, "execution_authority": "BLOCKED"}, sort_keys=True))


if __name__ == "__main__":
    main()
